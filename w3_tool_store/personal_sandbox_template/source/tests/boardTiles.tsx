import React from 'react';
import assert from 'node:assert/strict';
import { renderToStaticMarkup } from 'react-dom/server';
import { gridGeometry, placeBoardTile, removeBoardTile, sheetRects, tileImage } from '../core/boardTiles';
import { createEmptyProject } from '../core/project';
import { buildBackup, parseBackup, getStory, saveStory } from '../core/storage';
import { BoardWorkspace } from '../features/board/BoardWorkspace';
import type { BoardPack } from '../types';

const memory = new Map<string, string>();
(globalThis as any).localStorage = { getItem: (key: string) => memory.get(key) ?? null, setItem: (key: string, value: string) => memory.set(key, value), removeItem: (key: string) => memory.delete(key) };
assert.deepEqual(gridGeometry('seamless'), { gap: 0, radius: 0 });
assert.equal(gridGeometry('dots').gap, 5); assert.equal(gridGeometry('tiles').gap, 3); assert.equal(gridGeometry(undefined).gap, 3);
assert.deepEqual(sheetRects(34, 18, 2, 1, 1, 2), [{ x: 1, y: 1, width: 15, height: 16 }, { x: 18, y: 1, width: 15, height: 16 }]);
assert.equal(sheetRects(256, 256, 8, 8, 0, 0).length, 64);
for (const args of [[256,256,9,8,0,0], [10,10,0,1,0,0], [10,10,2,2,8,0], [10,10,1.5,1,0,0]]) assert.throws(() => sheetRects(...args as [number,number,number,number,number,number]));
const story = createEmptyProject('lego-test', 'library', 'เลโก้');
const board: BoardPack = { boardId: 'a', title: 'พื้นที่', width: 2, height: 2, gridStyle: 'seamless', showGridLines: false, cellMap: { '0_0': { x: 0, y: 0, name: 'ห้อง', desc: 'ข้อมูลเดิม', markerColor: '#ff0000', locationRefId: 'location' } }, explored: {}, visionRangeDefault: 2, movementPerTurnDefault: 2 };
story.boards = [board, { ...board, boardId: 'b' }];
story.boardTiles = [{ id: 'floor', name: 'พื้น', assetId: 'asset-floor' }];
story.assets['asset-floor'] = { id: 'asset-floor', name: 'พื้น', dataUrl: 'data:image/png;base64,YQ==' };
const placed = placeBoardTile(story, 'a', '0_0', 'floor');
assert.equal(placed.boards[0].cellMap['0_0'].tileRefId, 'floor');
assert.equal(placed.boards[0].cellMap['0_0'].locationRefId, 'location');
assert.equal(placed.boards[0].cellMap['0_0'].desc, 'ข้อมูลเดิม');
assert.equal(story.boards[0].cellMap['0_0'].tileRefId, undefined);
assert.equal(placed.boards[1].cellMap['0_0'].tileRefId, undefined);
assert.strictEqual(placeBoardTile(story, 'a', '9_0', 'floor'), story);
assert.strictEqual(placeBoardTile(story, 'a', '0_0', 'missing'), story);
assert.equal(saveStory(placed), true);
assert.equal(getStory(story.storyId)?.boards[0].gridStyle, 'seamless');
const restored = parseBackup(JSON.parse(JSON.stringify(buildBackup(placed))))!.story;
assert.equal(restored.boards[0].cellMap['0_0'].tileRefId, 'floor');
assert.equal(tileImage(restored.boardTiles!, restored.assets, 'floor'), story.assets['asset-floor'].dataUrl);
const erased = placeBoardTile(placed, 'a', '0_0');
assert.equal(erased.boards[0].cellMap['0_0'].tileRefId, undefined);
assert.equal(erased.boards[0].cellMap['0_0'].name, 'ห้อง');
const removed = removeBoardTile(placeBoardTile(placed, 'b', '1_1', 'floor'), 'floor');
assert.equal(removed.boardTiles?.length, 0);
assert.equal(removed.boards[0].cellMap['0_0'].tileRefId, undefined);
assert.equal(removed.boards[1].cellMap['1_1'].tileRefId, undefined);
const html = renderToStaticMarkup(<BoardWorkspace board={restored.boards[0]} selectedKey="0_0" zoom={22} tileImages={{ floor: story.assets['asset-floor'].dataUrl }} onZoom={() => {}} onAppearance={() => {}} onSelect={() => {}} onMode={() => {}} onAdd={() => {}} onUpdate={() => {}} onDelete={() => {}} />);
assert.ok(html.includes('gap:0')); assert.ok(html.includes('border-radius:0')); assert.ok(html.includes('border-width:0')); assert.ok(html.includes('box-shadow:none')); assert.ok(html.includes('data:image/png'));
assert.ok(html.includes('ช่องมน') && html.includes('จุด') && html.includes('กริดชิด'));
console.log('Board Lego: sheet geometry, seamless cells, data preservation, repeat placement, board isolation, erase/remove, storage, JSON and rendering passed');
